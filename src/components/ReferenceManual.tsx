'use client';

import { useCallback, useEffect, useMemo, useState } from 'react';
import { BookOpen, Download, FileText, Search } from 'lucide-react';
import { useApp } from '@/components/AppProvider';
import { Card, EmptyState, Skeleton, Toolbar } from '@/components/ui';
import {
  ApiError,
  api,
  downloadReport,
  type ServerManualChart,
  type ServerManualEntry,
  type ServerManualIndexItem,
} from '@/core/api/client';

/**
 * Reference Manual — the documented science behind all twenty tests.
 *
 * Layout notes that are requirements, not taste:
 *  * the manual body is English and therefore `dir="ltr"`, including the tables and the
 *    equations, whatever language the interface is in;
 *  * the search box filters on code, name, module and standard, because an analyst
 *    arrives with one of those four in mind;
 *  * the PDF is generated by the server from the same stored rows this screen renders,
 *    so the printed document and the screen can never disagree.
 */

/** A small, dependency-free chart: a line for x/y families, bars for single readings. */
function ManualChart({ chart }: { chart: ServerManualChart }) {
  const width = 560;
  const height = 190;
  const pad = { top: 12, right: 16, bottom: 30, left: 46 };

  if (chart.kind === 'line' && chart.points?.length) {
    const xs = chart.points.map((p) => p.x);
    const ys = chart.points.map((p) => p.y);
    const minX = Math.min(...xs);
    const maxX = Math.max(...xs);
    const minY = Math.min(...ys);
    const maxY = Math.max(...ys);
    const sx = (x: number) =>
      pad.left + ((x - minX) / (maxX - minX || 1)) * (width - pad.left - pad.right);
    const sy = (y: number) =>
      height - pad.bottom - ((y - minY) / (maxY - minY || 1)) * (height - pad.top - pad.bottom);
    const path = chart.points.map((p, i) => `${i === 0 ? 'M' : 'L'}${sx(p.x)},${sy(p.y)}`).join(' ');
    return (
      <svg viewBox={`0 0 ${width} ${height}`} className="w-full" role="img" aria-label={chart.y_label}>
        {[0, 0.25, 0.5, 0.75, 1].map((f) => (
          <line
            key={f}
            x1={pad.left}
            x2={width - pad.right}
            y1={pad.top + f * (height - pad.top - pad.bottom)}
            y2={pad.top + f * (height - pad.top - pad.bottom)}
            stroke="var(--border)"
            strokeDasharray="3 4"
          />
        ))}
        <path d={path} fill="none" stroke="var(--brand)" strokeWidth={2} />
        {chart.points.map((p, i) => (
          <circle key={i} cx={sx(p.x)} cy={sy(p.y)} r={3} fill="var(--brand)" />
        ))}
        <text x={width / 2} y={height - 8} textAnchor="middle" fontSize={10} fill="var(--text-muted)">
          {chart.x_label}
        </text>
        <text x={10} y={height / 2} fontSize={10} fill="var(--text-muted)" transform={`rotate(-90 10 ${height / 2})`} textAnchor="middle">
          {chart.y_label}
        </text>
      </svg>
    );
  }

  const bars = chart.bars ?? [];
  if (!bars.length) return null;
  const max = Math.max(...bars.map((b) => Math.abs(b.value))) || 1;
  const slot = (width - pad.left - pad.right) / bars.length;
  return (
    <svg viewBox={`0 0 ${width} ${height}`} className="w-full" role="img" aria-label={chart.y_label}>
      {bars.map((bar, i) => {
        const h = (Math.abs(bar.value) / max) * (height - pad.top - pad.bottom);
        return (
          <g key={i}>
            <rect
              x={pad.left + i * slot + slot * 0.2}
              y={height - pad.bottom - h}
              width={slot * 0.6}
              height={h}
              fill="var(--brand)"
              opacity={0.85}
              rx={2}
            />
            <text
              x={pad.left + i * slot + slot / 2}
              y={height - pad.bottom + 10}
              textAnchor="middle"
              fontSize={7.5}
              fill="var(--text-muted)"
            >
              {bar.label.length > 16 ? `${bar.label.slice(0, 15)}…` : bar.label}
            </text>
          </g>
        );
      })}
      <line
        x1={pad.left}
        x2={width - pad.right}
        y1={height - pad.bottom}
        y2={height - pad.bottom}
        stroke="var(--border)"
      />
      <text x={10} y={height / 2} fontSize={10} fill="var(--text-muted)" transform={`rotate(-90 10 ${height / 2})`} textAnchor="middle">
        {chart.y_label}
      </text>
    </svg>
  );
}

function limitText(row: ServerManualEntry['limits'][number]): string {
  const unit = row.unit ?? '';
  const trim = (v: string | null) => (v === null ? '' : String(Number(v)));
  if (row.operator === 'between') return `${trim(row.min_value)} – ${trim(row.max_value)} ${unit}`.trim();
  if (row.operator === 'lte') return `≤ ${trim(row.max_value)} ${unit}`.trim();
  if (row.operator === 'gte') return `≥ ${trim(row.min_value)} ${unit}`.trim();
  return `${row.operator} ${trim(row.min_value)} ${unit}`.trim();
}

export function ReferenceManual() {
  const { t, lang, notify } = useApp();
  const [index, setIndex] = useState<ServerManualIndexItem[]>([]);
  const [selected, setSelected] = useState<string>('T01');
  const [entry, setEntry] = useState<ServerManualEntry | null>(null);
  const [loadingIndex, setLoadingIndex] = useState(true);
  const [loadingEntry, setLoadingEntry] = useState(false);
  const [query, setQuery] = useState('');
  const [moduleFilter, setModuleFilter] = useState('ALL');
  const [printBusy, setPrintBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const data = await api.manualIndex();
        if (cancelled) return;
        setIndex(data.items);
      } catch (err) {
        if (!cancelled) {
          setError(err instanceof ApiError ? err.text(lang) : t('تعذر تحميل الدليل', 'The manual could not be loaded'));
        }
      } finally {
        if (!cancelled) setLoadingIndex(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [lang, t]);

  useEffect(() => {
    let cancelled = false;
    setLoadingEntry(true);
    (async () => {
      try {
        const data = await api.manualEntry(selected);
        if (!cancelled) setEntry(data);
      } catch (err) {
        if (!cancelled) {
          notify('error', t('تعذر تحميل القسم', 'Section not loaded'), err instanceof ApiError ? err.text(lang) : String(err));
        }
      } finally {
        if (!cancelled) setLoadingEntry(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [selected, lang, notify, t]);

  const modules = useMemo(
    () => ['ALL', ...Array.from(new Set(index.map((i) => i.module))).sort()],
    [index],
  );

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return index.filter((item) => {
      const byModule = moduleFilter === 'ALL' || item.module === moduleFilter;
      if (!byModule) return false;
      if (!q) return true;
      return (
        item.code.toLowerCase().includes(q) ||
        item.name_en.toLowerCase().includes(q) ||
        item.name_ar.includes(query.trim()) ||
        item.standard_ref.toLowerCase().includes(q)
      );
    });
  }, [index, moduleFilter, query]);

  const print = useCallback(
    async (scope: string) => {
      setPrintBusy(scope);
      try {
        await downloadReport(
          scope === 'ALL' ? '/reference-manual/manual.pdf' : `/reference-manual/${scope}/manual.pdf`,
          scope === 'ALL' ? 'SBDMA-Reference-Manual.pdf' : `SBDMA-Reference-Manual-${scope}.pdf`,
        );
        notify('success', t('تم توليد ملف الدليل', 'Manual PDF generated'), scope === 'ALL' ? t('الدليل الكامل', 'Full manual') : scope);
      } catch (err) {
        notify(
          'error',
          t('تعذر توليد الملف', 'The file could not be generated'),
          err instanceof ApiError ? err.text(lang) : String(err),
        );
      } finally {
        setPrintBusy(null);
      }
    },
    [lang, notify, t],
  );

  if (loadingIndex) return <Skeleton rows={10} />;

  return (
    <div className="grid gap-3 xl:grid-cols-[290px_1fr]" dir="ltr">
      <Card
        title="Reference Manual"
        subtitle={`${index.length} tests · English · LTR`}
        dense
        actions={
          <button
            className="btn btn-primary px-2 py-1 text-[11px]"
            onClick={() => void print('ALL')}
            disabled={printBusy !== null}
            title="Download the complete manual as a print-quality PDF"
          >
            <BookOpen size={13} /> {printBusy === 'ALL' ? 'Building…' : 'Full PDF'}
          </button>
        }
      >
        <div className="space-y-2 border-b p-2" style={{ borderColor: 'var(--border)' }}>
          <div className="relative">
            <Search size={13} className="absolute left-2 top-1/2 -translate-y-1/2 opacity-60" />
            <input
              className="input py-1 pl-7 text-[11.5px]"
              placeholder="Search code, name, standard…"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              aria-label="Search the reference manual"
            />
          </div>
          <select
            className="select py-1 text-[11.5px]"
            value={moduleFilter}
            onChange={(e) => setModuleFilter(e.target.value)}
            aria-label="Filter by module"
          >
            {modules.map((m) => (
              <option key={m} value={m}>
                {m === 'ALL' ? 'All modules' : m}
              </option>
            ))}
          </select>
        </div>
        <ul className="max-h-[600px] overflow-y-auto">
          {filtered.length === 0 && (
            <li className="p-3">
              <EmptyState title="No match" detail={query} />
            </li>
          )}
          {filtered.map((item) => (
            <li key={item.code}>
              <button
                onClick={() => setSelected(item.code)}
                className="flex w-full items-center gap-2 border-b px-3 py-2 text-left transition-colors"
                style={{
                  borderColor: 'var(--border)',
                  background: selected === item.code ? 'var(--brand-soft)' : 'transparent',
                }}
              >
                <span
                  className="shrink-0 rounded-md px-1.5 py-1 font-mono text-[10px] font-bold tabular-nums"
                  style={{ background: 'var(--surface-3)', color: 'var(--text)' }}
                >
                  {item.code}
                </span>
                <span className="min-w-0 flex-1">
                  <span className="block truncate text-[11.5px] font-semibold">{item.name_en}</span>
                  <span className="block truncate text-[10px]" style={{ color: 'var(--text-muted)' }}>
                    {item.module} · {item.readings_count} readings · {item.equations_count} equations
                  </span>
                </span>
                {!item.is_active && (
                  <span className="chip" style={{ background: 'rgba(180,35,24,.12)', color: 'var(--fail)' }}>
                    off
                  </span>
                )}
              </button>
            </li>
          ))}
        </ul>
      </Card>

      <div className="space-y-3">
        {error && (
          <Card title="Error">
            <p className="text-[12px]" style={{ color: 'var(--fail)' }}>
              {error}
            </p>
          </Card>
        )}
        {loadingEntry || !entry ? (
          <Skeleton rows={8} />
        ) : (
          <div className="space-y-3" dir="ltr" lang="en">
            <Card
              title={
                <span className="font-mono">
                  {entry.code} · {entry.name_en}
                </span>
              }
              subtitle={entry.standard_ref}
              actions={
                <Toolbar>
                  <span className="chip" style={{ background: 'var(--surface-3)' }}>
                    {entry.module}
                  </span>
                  <button
                    className="btn btn-ghost px-2 py-1 text-[11px]"
                    onClick={() => void print(entry.code)}
                    disabled={printBusy !== null}
                  >
                    <Download size={12} /> {printBusy === entry.code ? 'Building…' : 'PDF'}
                  </button>
                </Toolbar>
              }
            >
              <section className="space-y-3">
                <div>
                  <h4 className="mb-1 text-[11px] font-bold uppercase tracking-wide" style={{ color: 'var(--brand)' }}>
                    Overview &amp; importance
                  </h4>
                  <p className="text-[12px] leading-relaxed" style={{ color: 'var(--text-muted)' }}>
                    {entry.overview_en}
                  </p>
                </div>

                {entry.procedure_en.length > 0 && (
                  <div>
                    <h4 className="mb-1 text-[11px] font-bold uppercase tracking-wide" style={{ color: 'var(--brand)' }}>
                      Documented procedure
                    </h4>
                    <ol className="list-inside list-decimal space-y-1 text-[11.5px] leading-relaxed">
                      {entry.procedure_en.map((step, i) => (
                        <li key={i}>{step}</li>
                      ))}
                    </ol>
                  </div>
                )}
              </section>
            </Card>

            <Card title="Required readings and ideal values" dense>
              <div className="overflow-x-auto">
                <table className="table">
                  <thead>
                    <tr>
                      <th>Reading</th>
                      <th>Type</th>
                      <th>Unit</th>
                      <th>Required</th>
                      <th>Ideal value</th>
                      <th>Comment</th>
                    </tr>
                  </thead>
                  <tbody>
                    {entry.readings.map((row) => (
                      <tr key={row.key}>
                        <td className="text-[11.5px]">{row.label_en}</td>
                        <td className="font-mono text-[10.5px]">
                          {row.type === 'series' && row.length ? `series × ${row.length}` : row.type}
                        </td>
                        <td className="font-mono text-[10.5px]">{row.unit ?? '—'}</td>
                        <td className="text-[10.5px]">{row.required ? 'yes' : 'no'}</td>
                        <td className="font-mono text-[11px] font-bold tabular-nums">{row.ideal_value ?? '—'}</td>
                        <td className="text-[10.5px]" style={{ color: 'var(--text-muted)' }}>
                          {row.ideal_note ?? ''}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Card>

            <Card title="Mathematical equations" dense>
              <div className="overflow-x-auto">
                <table className="table">
                  <thead>
                    <tr>
                      <th>Key</th>
                      <th>Expression</th>
                      <th>Meaning</th>
                    </tr>
                  </thead>
                  <tbody>
                    {entry.equations.map((eq) => (
                      <tr key={eq.key}>
                        <td className="font-mono text-[10.5px] font-bold">{eq.key}</td>
                        <td>
                          <code
                            className="rounded px-1.5 py-0.5 font-mono text-[11px]"
                            style={{ background: 'var(--surface-2)' }}
                          >
                            {eq.expression}
                          </code>
                        </td>
                        <td className="text-[10.5px]" style={{ color: 'var(--text-muted)' }}>
                          {eq.description_en ?? '—'}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </Card>

            <div className="grid gap-3 lg:grid-cols-2">
              <Card title="Evaluation criteria" dense>
                <ul className="divide-y" style={{ borderColor: 'var(--border)' }}>
                  {entry.evaluation.map((row, i) => (
                    <li key={i} className="px-3 py-2">
                      <div className="font-mono text-[10.5px] font-bold">{row.metric}</div>
                      <div className="text-[11px]" style={{ color: 'var(--text-muted)' }}>
                        {row.text_en}
                      </div>
                    </li>
                  ))}
                </ul>
              </Card>

              <Card title="Acceptance limits" dense>
                <div className="overflow-x-auto">
                  <table className="table">
                    <thead>
                      <tr>
                        <th>Metric</th>
                        <th>Source</th>
                        <th>Limit</th>
                      </tr>
                    </thead>
                    <tbody>
                      {entry.limits.map((row, i) => {
                        const adopted =
                          row.source_type === 'AUTHORITY_LIMIT' && row.approval_status === 'APPROVED';
                        return (
                          <tr key={i} style={adopted ? { background: 'rgba(22,121,79,.07)' } : undefined}>
                            <td className="font-mono text-[10.5px]">{row.metric_key}</td>
                            <td className="text-[10px]">{row.source_type}</td>
                            <td className="font-mono text-[10.5px]">
                              {limitText(row)}
                              {row.approval_status === 'CONFLICT_REQUIRES_QA' && (
                                <span className="ms-1 chip" style={{ background: 'rgba(154,106,18,.15)', color: 'var(--warn, #9a6a12)' }}>
                                  QA
                                </span>
                              )}
                            </td>
                          </tr>
                        );
                      })}
                    </tbody>
                  </table>
                </div>
              </Card>
            </div>

            {entry.chart && (
              <Card
                title="Chart / calibration curve"
                subtitle={
                  entry.chart.kind === 'line'
                    ? `${entry.chart.y_label} against ${entry.chart.x_label}`
                    : entry.chart.y_label
                }
              >
                <ManualChart chart={entry.chart} />
              </Card>
            )}

            <Card title="Scientific references" dense>
              <ol className="list-inside list-decimal space-y-1 px-3 py-2 text-[11.5px]">
                {entry.references.map((ref, i) => (
                  <li key={i}>{ref}</li>
                ))}
              </ol>
              {entry.limit_notes.length > 0 && (
                <div className="border-t px-3 py-2 text-[10.5px]" style={{ borderColor: 'var(--border)', color: 'var(--text-muted)' }}>
                  {entry.limit_notes.map((note, i) => (
                    <p key={i} className="mb-1 flex gap-1.5">
                      <FileText size={11} className="mt-0.5 shrink-0" /> {note}
                    </p>
                  ))}
                </div>
              )}
            </Card>
          </div>
        )}
      </div>
    </div>
  );
}
