/**
 * SHIMADZU-LC2050C-UV-CAL v1.0.0
 * Every limit below is transcribed from the comparative report (matrix 2.1) and the
 * gap-closure matrix (2.4). Limits that the report classifies as defective or
 * conflicting are seeded as CONFLICT_REQUIRES_QA so the engine can never silently
 * issue a PASS on them.
 */

let seq = 0;
function L(
  testCode: string,
  metricKey: string,
  sourceType: LimitSource,
  operator: AcceptanceLimit['operator'],
  minValue: number | null,
  maxValue: number | null,
  unit: string,
  approvalStatus: AcceptanceLimit['approvalStatus'],
  note?: string,
  flagged?: boolean,
): AcceptanceLimit {
  seq += 1;
  return {
    id: `lim-${String(seq).padStart(4, '0')}`,
    testCode,
    metricKey,
    sourceType,
    operator,
    minValue,
    maxValue,
    unit,
    approvalStatus,
    approvedBy: approvalStatus === 'APPROVED' ? 'QA-APPROVER (seeded)' : null,
    approvedAt: approvalStatus === 'APPROVED' ? '2026-01-15T08:00:00.000Z' : null,
    note,
    flagged,
  };
}

